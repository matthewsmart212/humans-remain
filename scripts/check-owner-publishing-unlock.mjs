import assert from 'node:assert/strict';
import fs from 'node:fs';
import {build} from 'esbuild';
const compiled=await build({entryPoints:['server/edit-access.ts'],bundle:true,write:false,format:'esm',platform:'node',target:'node22'});
const {editorIdentity,editAccessResponse,editorUnlockResponse,editorLockResponse,editorOwnerLoginResponse}=await import('data:text/javascript;base64,'+Buffer.from(compiled.outputFiles[0].text).toString('base64'));
const origin='https://humans-remain.example.test',key='test-private-owner-key-with-more-than-32-characters',env={WORLD_EDITOR_TOKEN:key};
const post=(body,hostOrigin=origin)=>new Request(origin+'/api/editor-unlock',{method:'POST',headers:{Origin:hostOrigin,'Content-Type':'application/json'},body:JSON.stringify(body)});
const get=(headers={})=>new Request(origin+'/api/edit-access',{headers});
assert.equal((await editorIdentity(get(),env)).canEdit,false,'public visitor is never the owner');
assert.equal((await editorUnlockResponse(post({key}),{})).status,503,'unconfigured legacy unlock is not available');
assert.equal((await editorUnlockResponse(post({key:'not-it'}),env)).status,401,'incorrect private key rejected');
assert.equal((await editorUnlockResponse(post({key},'https://external.example'),env)).status,403,'foreign origin blocked');
assert.equal((await editorUnlockResponse(new Request(origin+'/api/editor-unlock'),env)).status,405);
const unlocked=await editorUnlockResponse(post({key}),env);
assert.equal(unlocked.status,200);
assert.equal((await unlocked.json()).canEdit,true);
const setCookie=unlocked.headers.get('Set-Cookie');
assert.match(setCookie,/HttpOnly/);
assert.match(setCookie,/Secure/);
assert.match(setCookie,/SameSite=Strict/);
assert.doesNotMatch((await(await editAccessResponse(get(),env)).text()),new RegExp(key),'private owner key is never returned by status endpoint');
const cookie=setCookie.split(';')[0];
const owner=get({Cookie:cookie});
assert.equal((await editorIdentity(owner,env)).canEdit,true,'existing owner cookies keep working');
assert.equal((await(await editAccessResponse(owner,env)).json()).state,'owner');
assert.equal((await editorIdentity(get({Cookie:'hr_editor_owner=invalid'}),env)).canEdit,false);
assert.equal((await editorIdentity(get({'oai-authenticated-user-id':'spoofed',Cookie:'hr_editor_owner=invalid'}),env)).canEdit,false,'public identity headers cannot bypass the lock');
assert.equal((await editorIdentity(get({Cookie:'hr_editor_owner=%BAD'}),env)).canEdit,false);
const locked=editorLockResponse(new Request(origin+'/api/editor-lock',{method:'POST',headers:{Origin:origin}}));
assert.equal(locked.status,200);
assert.match(locked.headers.get('Set-Cookie'),/Max-Age=0/);
assert.equal(editorLockResponse(new Request(origin+'/api/editor-lock',{method:'POST',headers:{Origin:'https://external.example'}})).status,403);
assert.equal(editorOwnerLoginResponse(get(),{},false).status,503,'unconfigured passwordless sign-in fails closed');
const configured={CF_ACCESS_TEAM_DOMAIN:'https://example.cloudflareaccess.com',CF_ACCESS_AUD:'test-audience',CF_ACCESS_OWNER_EMAIL:'owner@example.test'};
assert.equal(editorOwnerLoginResponse(get(),configured,false).status,403,'unauthenticated login route cannot grant owner');
assert.equal(editorOwnerLoginResponse(get(),configured,true).status,302,'only signed-in owners return to editor');
const editor=fs.readFileSync('src/WorldEditor.tsx','utf8');
assert(editor.includes("canEdit?'Publish World':'Sign in to publish'"),'World tab has owner sign-in action');
assert(editor.includes("canEdit?'Publish & Bundle World':'Sign in to publish'"),'mobile menu has owner sign-in action');
const access=fs.readFileSync('src/EditorAccess.tsx','utf8');
assert(access.includes("window.location.assign('/owner-login')"),'client uses passwordless sign-in path');
assert(!access.includes("fetch('/api/editor-unlock'"),'client never requests a private Cloudflare token');
assert(!access.includes('window.prompt('),'no client publish token prompt');
console.log('PASS: passwordless entry, no client key prompt, secure owner guard and legacy owner-cookie compatibility.');
