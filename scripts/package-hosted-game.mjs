import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {build} from 'esbuild';

const args=process.argv.slice(2),option=key=>args[args.indexOf(key)+1];
assert(args.includes('--destination')&&args.includes('--built-game')&&args.includes('--source-commit'),'Pass --destination, --built-game and --source-commit');
const destination=path.resolve(option('--destination')),built=path.resolve(option('--built-game')),commit=option('--source-commit');
assert(/^[0-9a-f]{40}$/.test(commit),'A complete verified GitHub source commit is required');
assert(destination!==process.cwd()&&destination!==built,'Use a separate hosting checkout');
const hosting=JSON.parse(fs.readFileSync(path.join(destination,'.openai/hosting.json'),'utf8'));
assert(hosting.project_id&&hosting.d1==='DB'&&hosting.r2==='ARTWORK','Configure the new Site and storage bindings first');
assert(fs.existsSync(path.join(built,'client/index.html')),'Build and validate the matching client first');
fs.mkdirSync(path.join(destination,'release'),{recursive:true});
fs.cpSync(path.join(built,'client'),path.join(destination,'release/client'),{recursive:true});
await build({entryPoints:['deploy/replica-worker.ts'],outfile:path.join(destination,'release/server/index.js'),bundle:true,platform:'neutral',format:'esm',target:'es2022',define:{__INDEX_HTML__:JSON.stringify(fs.readFileSync(path.join(built,'client/index.html'),'utf8'))}});
fs.cpSync('drizzle',path.join(destination,'drizzle'),{recursive:true});
fs.writeFileSync(path.join(destination,'package.json'),JSON.stringify({name:'humans-remain-hosted-release',version:'1.0.0',private:true,type:'module',scripts:{build:'node build-release.mjs'}},null,2)+'\n');
fs.writeFileSync(path.join(destination,'build-release.mjs'),`import fs from 'node:fs';
fs.rmSync('dist',{recursive:true,force:true});
fs.cpSync('release','dist',{recursive:true});
fs.mkdirSync('dist/.openai',{recursive:true});
fs.copyFileSync('.openai/hosting.json','dist/.openai/hosting.json');
fs.cpSync('drizzle','dist/.openai/drizzle',{recursive:true});
console.log('Prepared the verified Humans Remain release.');
`);
fs.writeFileSync(path.join(destination,'.gitignore'),'dist/\nnode_modules/\n.sites-runtime/\n.env*\n.rsync-tmp/\n.rsync-partial/\n');
fs.writeFileSync(path.join(destination,'release-source.json'),JSON.stringify({repository:'matthewsmart212/humans-remain',commit,world:'native/assets/world-snapshot.json',playerSavesImported:false},null,2)+'\n');
fs.writeFileSync(path.join(destination,'AGENTS.md'),'# Humans Remain hosting checkout\n\nThe shared development source is matthewsmart212/humans-remain. This checkout contains a built release. Make game changes in the latest shared GitHub source and regenerate this checkout with scripts/package-hosted-game.mjs; preserve its Site identity. Do not edit generated game bundles directly. Check release-source.json for the source revision.\n');
console.log(JSON.stringify({destination,project_id:hosting.project_id,github_commit:commit}));
