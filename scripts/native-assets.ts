import {GARDEN_ART} from '../src/camp-garden-art';
import {SPAWNABLES} from '../src/play-spawns';
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {installImportedArt} from '../src/imported-art';
import {prepareAuthoredWorld} from '../src/authored-world';
import {EDITOR_IMAGE_SOURCES,editorTerrainDetail} from '../src/editor-image-sources';
import {OUTDOOR_TILES} from '../src/outdoor-terrain';
import {TERRAIN_CHUNK_IMAGES} from '../src/terrain-stream-art';
import {RIVER_DETAIL_IMAGES} from '../src/river-art';
import {SCENES,sceneImages} from '../src/world-scenes';
import {requiredImages,WORLD_ASSETS} from '../src/world-assets';
import {libraryAssets} from '../src/asset-library-policy';
import {validateLayout} from '../src/world-layout';
import {WALKER_IMAGE_SOURCES} from '../src/walker-sprites';
import {BOMBER_IMAGE_SOURCES} from '../src/bomber-sprites';

// Refresh inputs explicitly before running. Generation itself is reproducible offline.
const root=process.cwd(),input=path.join(root,'.qa/native-world');
const art=JSON.parse(fs.readFileSync(path.join(input,'artwork.json'),'utf8'));
installImportedArt(art.records);
const raw=JSON.parse(fs.readFileSync(path.join(input,'world.json'),'utf8'));
const checked=validateLayout(raw.draft);if(!checked.layout||checked.errors.length)throw Error(checked.errors.join('; '));
const layout=prepareAuthoredWorld(checked.layout);
const sources={...Object.fromEntries(SPAWNABLES.map(v=>['spawn-thumb-'+v.id,v.image])),...EDITOR_IMAGE_SOURCES,...editorTerrainDetail(layout.terrainImage),
 ...Object.fromEntries(OUTDOOR_TILES.map(t=>[t.key,t.image])),...TERRAIN_CHUNK_IMAGES,...RIVER_DETAIL_IMAGES,
 ...Object.assign({},...[...SCENES.values()].map(sceneImages)),
 ...WALKER_IMAGE_SOURCES,...BOMBER_IMAGE_SOURCES,...requiredImages([...layout.items.map(p=>p.assetId),...GARDEN_ART.map(a=>a.id)],layout.terrainImage),
 ...Object.assign({},...[...SCENES.values()].map(s=>requiredImages(s.layout?.items.map(p=>p.assetId)||[])))};
const redirects=Object.assign({},...['lossless-artwork','retired-road','calm-river','river-features','river-quality'].map(n=>JSON.parse(fs.readFileSync(`server/${n}-redirects.json`,'utf8'))));
const canonical=(url:string)=>{const seen=new Set();while(redirects[url]){if(seen.has(url))throw Error('Redirect cycle');seen.add(url);url=redirects[url]}return url};
const modules:Record<string,string>={};
for(const url of [...new Set(Object.values(sources))].sort()){
 const resolved=canonical(url);let file:string;
 if(resolved.startsWith('/api/asset-files/')){
  const id=resolved.split('/').pop()!;if(!/^[a-z0-9-]+$/i.test(id))throw Error('Unexpected upload URL');
  file=`native/assets/world/${id}.png`;fs.mkdirSync(path.dirname(file),{recursive:true});
  if(!fs.existsSync(file))execFileSync('curl',['-fsSL','--retry','2','--max-time','60',`https://safety-last.matthew-smart212.chatgpt.site${resolved}`,'-o',file]);
 }else{if(!resolved.startsWith('/survival/'))throw Error('Unexpected game artwork '+resolved);file='public'+resolved}
 if(!fs.existsSync(file))throw Error('Missing current game artwork '+file);
 modules[url]='./'+path.relative('native',file).split(path.sep).join('/');
}
fs.writeFileSync('native/bundled-art.ts','// Generated by scripts/prepare-native-assets.mjs. Do not hand edit.\nexport const BUNDLED_ART:Record<string,number>={\n'+Object.entries(modules).map(([url,file])=>` ${JSON.stringify(url)}:require(${JSON.stringify(file)}),`).join('\n')+'\n};\n');
fs.writeFileSync('native/assets/world-snapshot.json',JSON.stringify({revision:raw.revision,layout,records:art.records}));
const keep=new Set(Object.values(modules).map(p=>path.resolve('native',p)));
// Include approved, unplaced editor assets and their complete states in cleanup protection.
const paletteIds=libraryAssets(WORLD_ASSETS).map(a=>a.id);
paletteIds.push(...WORLD_ASSETS.filter(a=>a.id.startsWith('wall-t2-')).map(a=>a.id));
for(const url of Object.values(requiredImages(paletteIds))){
 const resolved=canonical(url);if(resolved.startsWith('/survival/'))keep.add(path.resolve('public'+resolved));
}
keep.add(path.resolve('public/fonts/barlow-condensed-black.ttf'));
// Public manifests are source inputs for shared renderers and art tools.
for(const entry of fs.readdirSync('public/survival',{recursive:true}))if(String(entry).endsWith('.json'))keep.add(path.resolve('public/survival',String(entry)));
fs.writeFileSync(path.join(input,'asset-inventory.json'),JSON.stringify({placed:layout.items.length,bundled:Object.keys(modules).length,protected:[...keep].sort()},null,2));
console.log(JSON.stringify({placed:layout.items.length,bundled:Object.keys(modules).length,protected:keep.size}));
